-- Task78: preserve appointment history while enforcing current-term invariants.
-- btree_gist is a trusted PostgreSQL extension; the migration role needs CREATE
-- on this database (or a DBA must provision the extension beforehand).
CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE club_committee_assignments
    ADD COLUMN assignment_reason TEXT,
    ADD COLUMN replaces_assignment_id BIGINT REFERENCES club_committee_assignments(id) ON DELETE RESTRICT,
    ADD CONSTRAINT chk_committee_assignment_reason
        CHECK (assignment_reason IS NULL OR (length(btrim(assignment_reason)) BETWEEN 1 AND 2000)),
    ADD CONSTRAINT chk_committee_replaces_other CHECK (replaces_assignment_id IS NULL OR replaces_assignment_id <> id);

-- The old all-history key incorrectly prevents revoke-and-create at the same
-- start instant. Only unrevoked rows participate in logical uniqueness.
ALTER TABLE club_committee_assignments DROP CONSTRAINT uq_committee_membership_role_start;
CREATE UNIQUE INDEX uq_committee_active_term_start
    ON club_committee_assignments(membership_id, permission_role, starts_at)
    WHERE status = 'ACTIVE' AND revoked_at IS NULL;

-- Includes native INSERT/UPDATE paths; adjacent [start,end) terms remain valid.
-- Existing overlaps cause migration failure for operator resolution, never an
-- automatic revocation, date rewrite or destruction of historical evidence.
ALTER TABLE club_committee_assignments
    ADD CONSTRAINT excl_committee_active_term
    EXCLUDE USING gist (
        membership_id WITH =,
        permission_role WITH =,
        tstzrange(starts_at, ends_at, '[)') WITH &&
    ) WHERE (status = 'ACTIVE' AND revoked_at IS NULL);

CREATE TABLE committee_assignment_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT NOT NULL REFERENCES club_committee_assignments(id) ON DELETE RESTRICT,
    actor_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    action VARCHAR(20) NOT NULL CHECK (action IN ('ASSIGNED', 'REVOKED')),
    reason TEXT NOT NULL CHECK (length(btrim(reason)) BETWEEN 1 AND 2000),
    occurred_at TIMESTAMPTZ NOT NULL,
    trace_id UUID NOT NULL
);
CREATE INDEX idx_committee_assignment_audit_assignment
    ON committee_assignment_audit(assignment_id, occurred_at, id);
