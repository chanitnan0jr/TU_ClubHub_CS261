-- TU ClubHub: initial PostgreSQL domain schema (17 tables).
-- Source: TU-ClubHub-ERD-Updated.dbml provided by the team.
-- Run ONLY on an empty target schema; Flyway applies this migration once.
-- Spring Session JDBC tables are technical infrastructure created by V3.

-- 01 Identity ---------------------------------------------------------------
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tu_username VARCHAR(100) NOT NULL UNIQUE,
    display_name VARCHAR(200) NOT NULL,
    email VARCHAR(254),
    system_role VARCHAR(20) NOT NULL DEFAULT 'USER',
    account_status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_users_system_role CHECK (system_role IN ('USER', 'ADMIN')),
    CONSTRAINT chk_users_account_status CHECK (account_status IN ('ACTIVE', 'SUSPENDED'))
);

CREATE TABLE student_profiles (
    user_id BIGINT PRIMARY KEY,
    student_code VARCHAR(20) NOT NULL UNIQUE,
    faculty_name VARCHAR(200),
    department_name VARCHAR(200),
    program_name VARCHAR(200),
    study_year SMALLINT,
    student_status VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    synced_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_student_profiles_user FOREIGN KEY (user_id)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_student_profiles_study_year CHECK (study_year IS NULL OR study_year > 0),
    CONSTRAINT chk_student_profiles_status CHECK (student_status IN ('ACTIVE', 'INACTIVE', 'GRADUATED', 'UNKNOWN'))
);

-- 02 Club discovery --------------------------------------------------------
CREATE TABLE club_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE clubs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL UNIQUE,
    description TEXT NOT NULL,
    objectives TEXT,
    contact_url VARCHAR(2048),
    facebook_url VARCHAR(2048),
    instagram_url VARCHAR(2048),
    contact_email VARCHAR(254),
    affiliation_level VARCHAR(30),
    affiliation_name VARCHAR(200),
    image_url VARCHAR(2048),
    banner_url VARCHAR(2048),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_clubs_category FOREIGN KEY (category_id)
        REFERENCES club_categories(id) ON DELETE RESTRICT,
    CONSTRAINT fk_clubs_creator FOREIGN KEY (created_by)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_clubs_status CHECK (status IN ('ACTIVE', 'INACTIVE')),
    CONSTRAINT chk_clubs_contact_url CHECK (contact_url IS NULL OR contact_url ~* '^https://[^[:space:]]+$'),
    CONSTRAINT chk_clubs_image_url CHECK (image_url IS NULL OR image_url ~* '^https://[^[:space:]]+$'),
    CONSTRAINT chk_clubs_banner_url CHECK (banner_url IS NULL OR banner_url ~* '^https://[^[:space:]]+$'),
    CONSTRAINT chk_clubs_facebook_url CHECK (facebook_url IS NULL OR facebook_url ~* '^https://[^[:space:]]+$'),
    CONSTRAINT chk_clubs_instagram_url CHECK (instagram_url IS NULL OR instagram_url ~* '^https://[^[:space:]]+$')
);
CREATE INDEX idx_clubs_category_status ON clubs(category_id, status);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE club_tags (
    club_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    CONSTRAINT pk_club_tags PRIMARY KEY (club_id, tag_id),
    CONSTRAINT fk_club_tags_club FOREIGN KEY (club_id)
        REFERENCES clubs(id) ON DELETE CASCADE,
    CONSTRAINT fk_club_tags_tag FOREIGN KEY (tag_id)
        REFERENCES tags(id) ON DELETE CASCADE
);
CREATE INDEX idx_club_tags_tag ON club_tags(tag_id);

-- 03 Recruitment ------------------------------------------------------------
CREATE TABLE recruitment_rounds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL,
    title VARCHAR(200) NOT NULL,
    academic_year SMALLINT NOT NULL,
    semester SMALLINT NOT NULL,
    description TEXT NOT NULL,
    eligibility_text TEXT,
    opens_at TIMESTAMPTZ NOT NULL,
    closes_at TIMESTAMPTZ NOT NULL,
    closed_at TIMESTAMPTZ,
    results_scheduled_at TIMESTAMPTZ,
    confirmation_deadline TIMESTAMPTZ NOT NULL,
    publication_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at TIMESTAMPTZ,
    results_published_at TIMESTAMPTZ,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_recruitment_rounds_id_club UNIQUE (id, club_id),
    CONSTRAINT fk_recruitment_rounds_club FOREIGN KEY (club_id)
        REFERENCES clubs(id) ON DELETE RESTRICT,
    CONSTRAINT fk_recruitment_rounds_creator FOREIGN KEY (created_by)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_rounds_academic_year CHECK (academic_year > 0),
    CONSTRAINT chk_rounds_semester CHECK (semester > 0),
    CONSTRAINT chk_rounds_open_close CHECK (opens_at < closes_at),
    CONSTRAINT chk_rounds_manual_close CHECK (closed_at IS NULL OR (closed_at >= opens_at AND closed_at < closes_at)),
    CONSTRAINT chk_rounds_closed_published CHECK (closed_at IS NULL OR published_at IS NOT NULL),
    CONSTRAINT chk_rounds_results_schedule CHECK (
        results_scheduled_at IS NULL OR (results_scheduled_at >= opens_at AND results_scheduled_at < confirmation_deadline)
    ),
    CONSTRAINT chk_rounds_confirm_deadline CHECK (confirmation_deadline > closes_at),
    CONSTRAINT chk_rounds_publication_status CHECK (publication_status IN ('DRAFT', 'PUBLISHED', 'CANCELLED')),
    CONSTRAINT chk_rounds_publication_at CHECK (publication_status <> 'PUBLISHED' OR published_at IS NOT NULL),
    CONSTRAINT chk_rounds_results_published CHECK (
        results_published_at IS NULL OR (
            published_at IS NOT NULL AND results_published_at >= published_at
            AND results_published_at >= opens_at AND results_published_at < confirmation_deadline
        )
    )
);
CREATE INDEX idx_rounds_club_status_opens ON recruitment_rounds(club_id, publication_status, opens_at);
CREATE INDEX idx_rounds_year_semester_club ON recruitment_rounds(academic_year, semester, club_id);

CREATE TABLE application_questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT NOT NULL,
    prompt TEXT NOT NULL,
    is_required BOOLEAN NOT NULL DEFAULT true,
    display_order INTEGER NOT NULL,
    max_length INTEGER NOT NULL DEFAULT 2000,
    CONSTRAINT uq_questions_id_round UNIQUE (id, round_id),
    CONSTRAINT uq_questions_round_order UNIQUE (round_id, display_order),
    CONSTRAINT fk_questions_round FOREIGN KEY (round_id)
        REFERENCES recruitment_rounds(id) ON DELETE RESTRICT,
    CONSTRAINT chk_questions_order CHECK (display_order > 0),
    CONSTRAINT chk_questions_max_length CHECK (max_length > 0)
);

-- 04 Applications -----------------------------------------------------------
CREATE TABLE applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT NOT NULL,
    club_id BIGINT NOT NULL,
    applicant_id BIGINT NOT NULL,
    motivation TEXT NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'SUBMITTED',
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_by BIGINT,
    decided_at TIMESTAMPTZ,
    result_message TEXT,
    responded_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_applications_round_applicant UNIQUE (round_id, applicant_id),
    CONSTRAINT uq_applications_id_round UNIQUE (id, round_id),
    CONSTRAINT uq_applications_id_applicant_club UNIQUE (id, applicant_id, club_id),
    CONSTRAINT fk_applications_round_club FOREIGN KEY (round_id, club_id)
        REFERENCES recruitment_rounds(id, club_id) ON DELETE RESTRICT,
    CONSTRAINT fk_applications_applicant FOREIGN KEY (applicant_id)
        REFERENCES student_profiles(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_applications_decider FOREIGN KEY (decided_by)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_applications_status CHECK (
        status IN ('SUBMITTED', 'UNDER_REVIEW', 'ACCEPTED', 'REJECTED', 'CONFIRMED', 'DECLINED', 'WITHDRAWN', 'EXPIRED')
    ),
    CONSTRAINT chk_applications_decision_pair CHECK ((decided_by IS NULL) = (decided_at IS NULL)),
    CONSTRAINT chk_applications_decision_time CHECK (
        status NOT IN ('ACCEPTED', 'REJECTED', 'CONFIRMED', 'DECLINED', 'EXPIRED') OR decided_at IS NOT NULL
    ),
    CONSTRAINT chk_applications_response_time CHECK (
        (status IN ('CONFIRMED', 'DECLINED')) = (responded_at IS NOT NULL)
    )
);
CREATE INDEX idx_applications_applicant_submitted ON applications(applicant_id, submitted_at);
CREATE INDEX idx_applications_club_status ON applications(club_id, status);

CREATE TABLE application_answers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    round_id BIGINT NOT NULL,
    answer_text TEXT NOT NULL,
    CONSTRAINT uq_answers_application_question UNIQUE (application_id, question_id),
    CONSTRAINT fk_answers_application_round FOREIGN KEY (application_id, round_id)
        REFERENCES applications(id, round_id) ON DELETE RESTRICT,
    CONSTRAINT fk_answers_question_round FOREIGN KEY (question_id, round_id)
        REFERENCES application_questions(id, round_id) ON DELETE RESTRICT
);
CREATE INDEX idx_answers_question_round ON application_answers(question_id, round_id);

CREATE TABLE application_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    label VARCHAR(200) NOT NULL,
    url VARCHAR(2048) NOT NULL,
    display_order INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_links_application_order UNIQUE (application_id, display_order),
    CONSTRAINT fk_links_application FOREIGN KEY (application_id)
        REFERENCES applications(id) ON DELETE RESTRICT,
    CONSTRAINT chk_links_order CHECK (display_order > 0),
    CONSTRAINT chk_links_https CHECK (url ~* '^https://[^[:space:]]+$')
);

CREATE TABLE application_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    reviewer_id BIGINT NOT NULL,
    recommendation VARCHAR(20) NOT NULL,
    internal_comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_reviews_application_reviewer UNIQUE (application_id, reviewer_id),
    CONSTRAINT fk_reviews_application FOREIGN KEY (application_id)
        REFERENCES applications(id) ON DELETE RESTRICT,
    CONSTRAINT fk_reviews_reviewer FOREIGN KEY (reviewer_id)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_reviews_recommendation CHECK (recommendation IN ('ACCEPT', 'REJECT', 'DISCUSS'))
);
CREATE INDEX idx_reviews_reviewer ON application_reviews(reviewer_id);

CREATE TABLE application_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL,
    from_status VARCHAR(30),
    to_status VARCHAR(30) NOT NULL,
    actor_id BIGINT,
    reason TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_app_status_history_application FOREIGN KEY (application_id)
        REFERENCES applications(id) ON DELETE RESTRICT,
    CONSTRAINT fk_app_status_history_actor FOREIGN KEY (actor_id)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_app_history_from_status CHECK (
        from_status IS NULL OR from_status IN ('SUBMITTED', 'UNDER_REVIEW', 'ACCEPTED', 'REJECTED', 'CONFIRMED', 'DECLINED', 'WITHDRAWN', 'EXPIRED')
    ),
    CONSTRAINT chk_app_history_to_status CHECK (
        to_status IN ('SUBMITTED', 'UNDER_REVIEW', 'ACCEPTED', 'REJECTED', 'CONFIRMED', 'DECLINED', 'WITHDRAWN', 'EXPIRED')
    ),
    CONSTRAINT chk_app_history_change CHECK (from_status IS NULL OR from_status <> to_status)
);
CREATE INDEX idx_app_status_history_app_changed ON application_status_history(application_id, changed_at);

-- 05 Membership ------------------------------------------------------------
CREATE TABLE club_memberships (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    source_application_id BIGINT UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    joined_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_memberships_club_user UNIQUE (club_id, user_id),
    CONSTRAINT fk_memberships_club FOREIGN KEY (club_id)
        REFERENCES clubs(id) ON DELETE RESTRICT,
    CONSTRAINT fk_memberships_student FOREIGN KEY (user_id)
        REFERENCES student_profiles(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_memberships_source_application FOREIGN KEY (source_application_id, user_id, club_id)
        REFERENCES applications(id, applicant_id, club_id) ON DELETE RESTRICT,
    CONSTRAINT chk_memberships_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'LEFT', 'REMOVED')),
    CONSTRAINT chk_memberships_end_status CHECK ((status IN ('LEFT', 'REMOVED')) = (ended_at IS NOT NULL)),
    CONSTRAINT chk_memberships_end_date CHECK (ended_at IS NULL OR ended_at >= joined_at)
);
CREATE INDEX idx_memberships_user_status ON club_memberships(user_id, status);
CREATE INDEX idx_memberships_club_status ON club_memberships(club_id, status);

CREATE TABLE club_committee_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL,
    position_name VARCHAR(100) NOT NULL,
    permission_role VARCHAR(20) NOT NULL DEFAULT 'COMMITTEE',
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    assigned_by BIGINT NOT NULL,
    revoked_by BIGINT,
    revoked_at TIMESTAMPTZ,
    revocation_reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_committee_membership_role_start UNIQUE (membership_id, permission_role, starts_at),
    CONSTRAINT fk_committee_membership FOREIGN KEY (membership_id)
        REFERENCES club_memberships(id) ON DELETE RESTRICT,
    CONSTRAINT fk_committee_assigner FOREIGN KEY (assigned_by)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_committee_revoker FOREIGN KEY (revoked_by)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_committee_role CHECK (permission_role IN ('COMMITTEE', 'PRESIDENT')),
    CONSTRAINT chk_committee_status CHECK (status IN ('ACTIVE', 'REVOKED')),
    CONSTRAINT chk_committee_period CHECK (starts_at < ends_at),
    CONSTRAINT chk_committee_revoked_status CHECK ((status = 'REVOKED') = (revoked_at IS NOT NULL)),
    CONSTRAINT chk_committee_revoker_pair CHECK ((revoked_at IS NULL) = (revoked_by IS NULL)),
    CONSTRAINT chk_committee_revoked_at CHECK (revoked_at IS NULL OR revoked_at >= created_at)
);
CREATE INDEX idx_committee_membership_status_term
    ON club_committee_assignments(membership_id, status, starts_at, ends_at);

CREATE TABLE membership_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    membership_id BIGINT NOT NULL,
    old_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    actor_id BIGINT,
    reason TEXT,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT fk_membership_history_membership FOREIGN KEY (membership_id)
        REFERENCES club_memberships(id) ON DELETE RESTRICT,
    CONSTRAINT fk_membership_history_actor FOREIGN KEY (actor_id)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT chk_membership_history_old CHECK (old_status IS NULL OR old_status IN ('ACTIVE', 'INACTIVE', 'LEFT', 'REMOVED')),
    CONSTRAINT chk_membership_history_new CHECK (new_status IN ('ACTIVE', 'INACTIVE', 'LEFT', 'REMOVED')),
    CONSTRAINT chk_membership_history_change CHECK (old_status IS NULL OR old_status <> new_status)
);
CREATE INDEX idx_membership_history_membership_changed ON membership_history(membership_id, changed_at);

-- 06 Notifications ---------------------------------------------------------
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    application_id BIGINT,
    membership_id BIGINT,
    type VARCHAR(30) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message TEXT NOT NULL,
    deduplication_key VARCHAR(200) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at TIMESTAMPTZ,
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id)
        REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_application FOREIGN KEY (application_id)
        REFERENCES applications(id) ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_membership FOREIGN KEY (membership_id)
        REFERENCES club_memberships(id) ON DELETE RESTRICT,
    CONSTRAINT chk_notifications_type CHECK (
        type IN ('APPLICATION_SUBMITTED', 'RESULT_PUBLISHED', 'APPLICATION_CONFIRMED', 'MEMBERSHIP_UPDATED')
    ),
    CONSTRAINT chk_notifications_read_at CHECK (read_at IS NULL OR read_at >= created_at),
    CONSTRAINT chk_notifications_parent CHECK (
        (type = 'MEMBERSHIP_UPDATED' AND membership_id IS NOT NULL AND application_id IS NULL)
        OR (type <> 'MEMBERSHIP_UPDATED' AND application_id IS NOT NULL AND membership_id IS NULL)
    )
);
CREATE INDEX idx_notifications_recipient_unread_created ON notifications(recipient_id, read_at, created_at);
