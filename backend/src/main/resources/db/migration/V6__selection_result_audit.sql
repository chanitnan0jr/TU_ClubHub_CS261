-- Durable mutation audit, distinct from application status history. No private notes/answers.
CREATE TABLE selection_result_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    round_id BIGINT NOT NULL,
    club_id BIGINT NOT NULL REFERENCES clubs(id),
    application_id BIGINT REFERENCES applications(id),
    actor_id BIGINT NOT NULL REFERENCES users(id),
    action VARCHAR(40) NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    trace_id UUID NOT NULL,
    before_state JSONB NOT NULL,
    after_state JSONB NOT NULL,
    CONSTRAINT fk_selection_result_audit_round_club FOREIGN KEY (round_id, club_id)
        REFERENCES recruitment_rounds(id, club_id),
    CONSTRAINT chk_selection_result_audit_action CHECK (
        (action = 'DECISION_RECORDED' AND application_id IS NOT NULL)
        OR (action = 'RESULTS_PUBLISHED' AND application_id IS NULL)
    ),
    CONSTRAINT chk_selection_result_audit_state CHECK (
        jsonb_typeof(before_state) = 'object' AND jsonb_typeof(after_state) = 'object'
    )
);
CREATE INDEX idx_selection_result_audit_round ON selection_result_audit(round_id, occurred_at, id);
CREATE INDEX idx_selection_result_audit_application ON selection_result_audit(application_id, occurred_at, id);
