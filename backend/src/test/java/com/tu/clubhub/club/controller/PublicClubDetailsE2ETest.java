    private static final Long ACTIVE_CLUB_ID = 51L;
    private static final Long INACTIVE_CLUB_ID = 52L;

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private JdbcTemplate jdbcTemplate;

    @Autowired
    private ClubRepository clubRepository;

    @Autowired
    private UserAccountRepository userAccountRepository;

    private Long categoryId;
    private Long tagId;
    private String tagName;

    @BeforeEach
    void setUp() {
        // Ensure auxiliary tables for JdbcTemplate queries exist in H2 schema
        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS club_categories (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(100) NOT NULL UNIQUE,
                description TEXT
            )
            """);
        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS tags (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(80) NOT NULL UNIQUE
            )
            """);
        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS club_tags (
                club_id BIGINT NOT NULL,
                tag_id BIGINT NOT NULL,
                PRIMARY KEY (club_id, tag_id)
            )
            """);
        jdbcTemplate.execute("""
            CREATE TABLE IF NOT EXISTS recruitment_rounds (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                club_id BIGINT NOT NULL,
                title VARCHAR(200) NOT NULL,
                publication_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
                opens_at TIMESTAMP WITH TIME ZONE,
                closes_at TIMESTAMP WITH TIME ZONE,
                closed_at TIMESTAMP WITH TIME ZONE
            )
            """);

        clubRepository.deleteAll();
        userAccountRepository.deleteAll();
        jdbcTemplate.execute("DELETE FROM club_tags");
        jdbcTemplate.execute("DELETE FROM tags");
        jdbcTemplate.execute("DELETE FROM club_categories");
        jdbcTemplate.execute("DELETE FROM recruitment_rounds");

        // Insert Category
        jdbcTemplate.update(
                "INSERT INTO club_categories (id, name, description) VALUES (1, ?, ?)",
                "บำเพ็ญประโยชน์และจิตอาสา", "หมวดกิจกรรมเพื่อสังคม");
        categoryId = 1L;

        // Insert Tag
        tagName = "จิตอาสา";
        tagId = 1L;
        jdbcTemplate.update("INSERT INTO tags (id, name) VALUES (?, ?)", tagId, tagName);

        // Insert Creator User
        UserAccount creator = userAccountRepository.saveAndFlush(
                new UserAccount("creator-" + UUID.randomUUID(), "ผู้ดูแลระบบ", "admin@tu.ac.th", Instant.now()));

        // Insert Active Club
        jdbcTemplate.update("""
            INSERT INTO clubs (id, category_id, name, description, objectives, contact_email,
                              contact_url, facebook_url, instagram_url, image_url, banner_url,
                              affiliation_level, affiliation_name, status, created_by,
                              created_at, updated_at, version)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'ACTIVE', ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 0)
            """,
                ACTIVE_CLUB_ID, categoryId, "ชมรมอาสาพัฒนา มธ.",
                "ส่งเสริมการทำกิจกรรมเพื่อพัฒนาชุมชนและสังคม", "เพื่อฝึกฝนทักษะการทำงานเป็นทีมและช่วยเหลือสังคม",
                "volunteer@tu.ac.th", "https://volunteer.tu.ac.th", "https://facebook.com/tuvolunteer",
                "https://instagram.com/tuvolunteer", "https://example.com/logo.png", "https://example.com/banner.png",
                "มหาวิทยาลัย", "มหาวิทยาลัยธรรมศาสตร์", creator.getId());

        // Link Tag
        jdbcTemplate.update("INSERT INTO club_tags (club_id, tag_id) VALUES (?, ?)", ACTIVE_CLUB_ID, tagId);

        // Insert Inactive Club
        jdbcTemplate.update("""
            INSERT INTO clubs (id, category_id, name, description, objectives, contact_email,
                              status, created_by, created_at, updated_at, version)
            VALUES (?, ?, ?, ?, ?, ?, 'INACTIVE', ?, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 0)
            """,
                INACTIVE_CLUB_ID, categoryId, "ชมรมที่ปิดตัวแล้ว", "คำอธิบาย", "วัตถุประสงค์",
                "inactive@tu.ac.th", creator.getId());
    }

    private static long nextRoundId = 100L;

    private Long insertRound(Long clubId, String title, String status, Instant opensAt, Instant closesAt, Instant closedAt) {
        OffsetDateTime openTime = opensAt != null ? OffsetDateTime.ofInstant(opensAt, ZoneOffset.UTC) : null;
        OffsetDateTime closeTime = closesAt != null ? OffsetDateTime.ofInstant(closesAt, ZoneOffset.UTC) : null;
        OffsetDateTime closedTime = closedAt != null ? OffsetDateTime.ofInstant(closedAt, ZoneOffset.UTC) : null;

        long id = ++nextRoundId;
        jdbcTemplate.update("""
            INSERT INTO recruitment_rounds (id, club_id, title, publication_status, opens_at, closes_at, closed_at)
            VALUES (?, ?, ?, ?, ?, ?, ?)
            """, id, clubId, title, status, openTime, closeTime, closedTime);
        return id;
    }

    // =========================================================================
    // TC-02-01: ผู้ใช้ไม่ได้ Login เปิด URL ชมรมสาธารณะโดยตรง (Direct Access Without Login)
    // =========================================================================
    @Nested
    @DisplayName("TC-02-01: ผู้ใช้ไม่ได้ Login เปิดดูข้อมูลสาธารณะของชมรมได้โดยไม่ต้องยืนยันตัวตน")
    class TestCase02_01 {

        @Test
        @DisplayName("TC-02-01A: Anonymous Access สำเร็จ และส่งคืนเฉพาะข้อมูลสาธารณะ (ไม่ส่งฟิลด์ภายใน)")
        void anonymousCanAccessPublicProfile() throws Exception {
            mockMvc.perform(get("/api/v1/public/clubs/{id}", ACTIVE_CLUB_ID))
                    .andExpect(status().isOk())
                    .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
                    .andExpect(jsonPath("$.id").value(ACTIVE_CLUB_ID.toString()))
                    .andExpect(jsonPath("$.name").value("ชมรมอาสาพัฒนา มธ."))
                    .andExpect(jsonPath("$.description").value("ส่งเสริมการทำกิจกรรมเพื่อพัฒนาชุมชนและสังคม"))
                    .andExpect(jsonPath("$.objectives").value("เพื่อฝึกฝนทักษะการทำงานเป็นทีมและช่วยเหลือสังคม"))
                    .andExpect(jsonPath("$.contactEmail").value("volunteer@tu.ac.th"))
                    .andExpect(jsonPath("$.contactUrl").value("https://volunteer.tu.ac.th"))
                    .andExpect(jsonPath("$.facebookUrl").value("https://facebook.com/tuvolunteer"))
                    .andExpect(jsonPath("$.instagramUrl").value("https://instagram.com/tuvolunteer"))
                    .andExpect(jsonPath("$.imageUrl").value("https://example.com/logo.png"))
                    .andExpect(jsonPath("$.bannerUrl").value("https://example.com/banner.png"))
                    .andExpect(jsonPath("$.affiliationLevel").value("มหาวิทยาลัย"))
                    .andExpect(jsonPath("$.affiliationName").value("มหาวิทยาลัยธรรมศาสตร์"))
                    .andExpect(jsonPath("$.category.id").value(categoryId.toString()))
                    .andExpect(jsonPath("$.category.name").value("บำเพ็ญประโยชน์และจิตอาสา"))
                    .andExpect(jsonPath("$.tags", hasSize(1)))
                    .andExpect(jsonPath("$.tags[0].name").value("จิตอาสา"))
                    // ตรวจสอบว่าไม่มีฟิลด์ภายใน เช่น version, createdBy, status หลุดออกมา
                    .andExpect(jsonPath("$.keys()", containsInAnyOrder(
                            "id", "name", "description", "objectives", "contactUrl",
                            "facebookUrl", "instagramUrl", "contactEmail", "affiliationLevel",
                            "affiliationName", "imageUrl", "bannerUrl", "category", "tags")));
        }
    }

    // =========================================================================
    // TC-02-02: ชมรมมีรอบที่เปิดรับสมัคร (Active Published Recruitment Round)
    // =========================================================================
    @Nested
    @DisplayName("TC-02-02: แสดงรอบรับสมัครที่เปิดอยู่ และมีข้อมูลสำหรับนำทางไปสมัคร")
    class TestCase02_02 {

        @Test
        @DisplayName("TC-02-02A: รอบ Published ที่อยู่ในช่วงเวลาเปิดรับ แสดงผลอย่างถูกต้อง")
        void activePublishedRoundIsReturned() throws Exception {
            Instant now = Instant.now();
            Long roundId = insertRound(ACTIVE_CLUB_ID, "รอบรับสมัครสมาชิกใหม่ 1/2569", "PUBLISHED",
                    now.minusSeconds(3600), now.plusSeconds(86400), null);

            mockMvc.perform(get("/api/v1/public/clubs/{id}/recruitment-rounds", ACTIVE_CLUB_ID))
                    .andExpect(status().isOk())
                    .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
                    .andExpect(jsonPath("$.items", hasSize(1)))
                    .andExpect(jsonPath("$.items[0].id").value(roundId.toString()))
                    .andExpect(jsonPath("$.items[0].name").value("รอบรับสมัครสมาชิกใหม่ 1/2569"))
                    .andExpect(jsonPath("$.page.totalElements").value(1));
        }
    }

    // =========================================================================
    // TC-02-03: มีเฉพาะรอบในอนาคตหรือรอบที่ปิดรับแล้ว (Future, Expired, Closed Rounds)
    // =========================================================================
    @Nested
    @DisplayName("TC-02-03: กรองรอบในอนาคต รอบที่หมดเขต และรอบที่ปิดรับด้วยมือออกจาก Public API")
    class TestCase02_03 {

        @Test
        @DisplayName("TC-02-03A: ไม่ส่งคืนรอบที่ยังไม่ถึงเวลาเปิด หรือหมดเวลาแล้ว หรือปิดรับแล้ว")
        void excludesNonActiveRounds() throws Exception {
            Instant now = Instant.now();
            // รอบอนาคต (opens in 1 day)
            insertRound(ACTIVE_CLUB_ID, "รอบอนาคต", "PUBLISHED", now.plusSeconds(86400), now.plusSeconds(172800), null);
            // รอบอดีตที่หมดเขตแล้ว (closed yesterday)
            insertRound(ACTIVE_CLUB_ID, "รอบอดีต", "PUBLISHED", now.minusSeconds(172800), now.minusSeconds(86400), null);
            // รอบที่ปิดรับก่อนกำหนดด้วยมือ
            insertRound(ACTIVE_CLUB_ID, "รอบปิดด้วยมือ", "PUBLISHED", now.minusSeconds(86400), now.plusSeconds(86400), now.minusSeconds(10));

            mockMvc.perform(get("/api/v1/public/clubs/{id}/recruitment-rounds", ACTIVE_CLUB_ID))
                    .andExpect(status().isOk())
                    .andExpect(jsonPath("$.items", hasSize(0)))
                    .andExpect(jsonPath("$.page.totalElements").value(0));
        }
    }

    // =========================================================================
    // TC-02-04: ชมรมไม่มีรอบรับสมัคร หรือมีเฉพาะรอบ Draft
    // =========================================================================
    @Nested
    @DisplayName("TC-02-04: ชมรมไม่มีรอบรับสมัคร หรือมีเฉพาะรอบ Draft ต้องส่งคืนรายการว่าง")
    class TestCase02_04 {

        @Test
        @DisplayName("TC-02-04A: มีเฉพาะรอบ Draft ต้องไม่ส่งคืน และไม่เปิดเผยข้อมูล Draft สู่สาธารณะ")
        void draftOnlyReturnsEmptyList() throws Exception {
            Instant now = Instant.now();
            Long draftId = insertRound(ACTIVE_CLUB_ID, "รอบฉบับร่างที่ซ่อนอยู่", "DRAFT",
                    now.minusSeconds(3600), now.plusSeconds(86400), null);

            mockMvc.perform(get("/api/v1/public/clubs/{id}/recruitment-rounds", ACTIVE_CLUB_ID))
                    .andExpect(status().isOk())
                    .andExpect(jsonPath("$.items", hasSize(0)))
                    .andExpect(jsonPath("$.items[*].id", not(hasItem(draftId.toString()))))
                    .andExpect(jsonPath("$.page.totalElements").value(0));
        }
    }

    // =========================================================================
    // TC-02-05: มีทั้งรอบ Published และ Draft พร้อมกัน (Isolation of Draft Data)
    // =========================================================================
    @Nested
    @DisplayName("TC-02-05: ส่งเฉพาะรอบ Published ที่เปิดรับอยู่ และแยกแยะข้อมูล Draft ออกอย่างสมบูรณ์")
    class TestCase02_05 {

        @Test
        @DisplayName("TC-02-05A: ส่งคืนเฉพาะรอบ Published โดยกรองรอบ Draft ทิ้ง 100%")
        void mixedPublishedAndDraftOnlyReturnsPublished() throws Exception {
            Instant now = Instant.now();
            Long publishedId = insertRound(ACTIVE_CLUB_ID, "รอบเปิดรับจริง", "PUBLISHED",
                    now.minusSeconds(3600), now.plusSeconds(86400), null);
            Long draftId = insertRound(ACTIVE_CLUB_ID, "รอบ Draft ลับ", "DRAFT",
                    now.minusSeconds(3600), now.plusSeconds(86400), null);

            mockMvc.perform(get("/api/v1/public/clubs/{id}/recruitment-rounds", ACTIVE_CLUB_ID))
                    .andExpect(status().isOk())
                    .andExpect(jsonPath("$.items", hasSize(1)))
                    .andExpect(jsonPath("$.items[0].id").value(publishedId.toString()))
                    .andExpect(jsonPath("$.items[0].name").value("รอบเปิดรับจริง"))
                    .andExpect(jsonPath("$.items[*].id", not(hasItem(draftId.toString()))))
                    .andExpect(jsonPath("$.page.totalElements").value(1));
        }
    }

