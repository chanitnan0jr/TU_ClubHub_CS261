    // =========================================================================
    @Nested
    @DisplayName("TC-06-07: ล้างข้อมูลฟิลด์ไม่บังคับและ HTTP Method ไม่ถูกต้อง")
    class TestCase06_07 {

        @Test
        @DisplayName("7A: ล้างค่าฟิลด์ทางเลือกด้วย null สำเร็จและไม่กระทบฟิลด์สงวน")
        void nullifyOptionalFieldsSuccess() throws Exception {
            String payload = """
                {
                  "name": "ชมรมดนตรีสากล",
                  "description": "คำอธิบายชมรม",
                  "objectives": null,
                  "contactUrl": null,
                  "facebookUrl": null,
                  "instagramUrl": null,
                  "contactEmail": null,
                  "imageUrl": null,
                  "bannerUrl": null
                }
                """;

            mockMvc.perform(put("/api/v1/clubs/{clubId}", TARGET_CLUB_ID)
                            .with(authentication(authFor(committeeAccount)))
                            .with(csrf())
                            .contentType(MediaType.APPLICATION_JSON)
                            .content(payload))
                    .andExpect(status().isOk())
                    .andExpect(jsonPath("$.name").value("ชมรมดนตรีสากล"))
                    .andExpect(jsonPath("$.description").value("คำอธิบายชมรม"))
                    .andExpect(jsonPath("$.objectives").value(nullValue()))
                    .andExpect(jsonPath("$.contactEmail").value(nullValue()))
                    .andExpect(jsonPath("$.facebookUrl").value(nullValue()))
                    .andExpect(jsonPath("$.instagramUrl").value(nullValue()))
                    .andExpect(jsonPath("$.imageUrl").value(nullValue()))
                    .andExpect(jsonPath("$.bannerUrl").value(nullValue()));

            Club club = clubRepository.findById(TARGET_CLUB_ID).orElseThrow();
            assertNull(club.getObjectives());
            assertNull(club.getContactEmail());
            assertNull(club.getFacebookUrl());
            assertNull(club.getInstagramUrl());
            assertNull(club.getImageUrl());
            assertNull(club.getBannerUrl());
            // Immutable fields preserved
            assertEquals(categoryId, club.getCategoryId());
            assertEquals("ACTIVE", club.getStatus());
        }

        @Test
        @DisplayName("7C: คำขอด้วย HTTP Method ที่ไม่รองรับ (DELETE) คืนค่า 405 METHOD_NOT_ALLOWED")
        void unsupportedMethodReturns405() throws Exception {
            mockMvc.perform(delete("/api/v1/clubs/{clubId}", TARGET_CLUB_ID)
                            .with(authentication(authFor(committeeAccount)))
                            .with(csrf()))
                    .andExpect(status().isMethodNotAllowed())
                    .andExpect(header().string("Allow", containsString("PUT")));
        }
    }
