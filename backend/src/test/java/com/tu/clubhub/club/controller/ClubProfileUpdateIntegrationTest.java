    // TC-06-01: แก้ไขชื่อ คำอธิบาย และวัตถุประสงค์สำเร็จ (Positive Case)
    // =========================================================================
    @Nested
    @DisplayName("TC-06-01: แก้ไขชื่อ คำอธิบาย และวัตถุประสงค์สำเร็จ")
    class TestCase06_01 {

        @Test
        @DisplayName("แก้ไขข้อมูลพื้นฐานสำเร็จและรักษาฟิลด์สงวน (Immutable fields)")
        void updateBasicInfoSuccess() throws Exception {
            String payload = """
                {
                  "name": "ชมรมดนตรีสากล มหาวิทยาลัยธรรมศาสตร์ (Updated)",
                  "description": "ชมรมสำหรับผู้รักในเสียงดนตรีและศิลปะการแสดงร่วมสมัย",
                  "objectives": "เพื่อส่งเสริมทักษะดนตรีสากลและสร้างสรรค์กิจกรรมดนตรีในมหาวิทยาลัย"
                }
                """;

            mockMvc.perform(put("/api/v1/clubs/{clubId}", TARGET_CLUB_ID)
                            .with(authentication(authFor(committeeAccount)))
                            .with(csrf())
                            .contentType(MediaType.APPLICATION_JSON)
                            .content(payload))
                    .andExpect(status().isOk())
                    .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
                    .andExpect(jsonPath("$.id").value(TARGET_CLUB_ID.toString()))
                    .andExpect(jsonPath("$.name").value("ชมรมดนตรีสากล มหาวิทยาลัยธรรมศาสตร์ (Updated)"))
                    .andExpect(jsonPath("$.description").value("ชมรมสำหรับผู้รักในเสียงดนตรีและศิลปะการแสดงร่วมสมัย"))
                    .andExpect(jsonPath("$.objectives").value("เพื่อส่งเสริมทักษะดนตรีสากลและสร้างสรรค์กิจกรรมดนตรีในมหาวิทยาลัย"))
                    .andExpect(jsonPath("$.category.id").value(categoryId.toString()))
                    .andExpect(jsonPath("$.category.name").value("ดนตรีและศิลปะการแสดง"))
                    .andExpect(jsonPath("$.tags", hasSize(1)))
                    .andExpect(jsonPath("$.tags[0].name").value("ดนตรีสากล"))
                    .andExpect(jsonPath("$.status").value("ACTIVE"));

            // Verify Database Row
            Club club = clubRepository.findById(TARGET_CLUB_ID).orElseThrow();
            assertEquals("ชมรมดนตรีสากล มหาวิทยาลัยธรรมศาสตร์ (Updated)", club.getName());
            assertEquals("ชมรมสำหรับผู้รักในเสียงดนตรีและศิลปะการแสดงร่วมสมัย", club.getDescription());
            assertEquals("เพื่อส่งเสริมทักษะดนตรีสากลและสร้างสรรค์กิจกรรมดนตรีในมหาวิทยาลัย", club.getObjectives());
            // Immutable fields
            assertEquals(categoryId, club.getCategoryId());
            assertEquals("ACTIVE", club.getStatus());
            assertEquals("UNIVERSITY", club.getAffiliationLevel());
            assertEquals("องค์การนักศึกษามหาวิทยาลัยธรรมศาสตร์", club.getAffiliationName());
            assertEquals(committeeAccount.getId(), club.getCreatedBy());
        }
    }

