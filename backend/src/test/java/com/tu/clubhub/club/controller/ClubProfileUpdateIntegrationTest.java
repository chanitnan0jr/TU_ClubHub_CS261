    private void grantCommittee(Long clubId, UserAccount user, String role, Instant startsAt, Instant endsAt) {
        ClubMembership membership = membershipRepository.saveAndFlush(
                new ClubMembership(clubId, user.getId(), "ACTIVE"));
        jdbcTemplate.update(
            "UPDATE club_memberships SET joined_at = ? WHERE id = ?",
            java.sql.Timestamp.from(Instant.now().minusSeconds(60)),
            membership.getId());
        assignmentRepository.saveAndFlush(
                new ClubCommitteeAssignment(membership.getId(), "Committee", role, startsAt, endsAt, user.getId()));
    }

    private String targetClubName() {
        return jdbcTemplate.queryForObject("SELECT name FROM clubs WHERE id = ?", String.class, TARGET_CLUB_ID);
    }

    private UsernamePasswordAuthenticationToken authFor(UserAccount account) {
        ClubHubPrincipal principal = new ClubHubPrincipal(account.getId(), account.getTuUsername(), "USER");
        return UsernamePasswordAuthenticationToken.authenticated(principal, null, List.of());
    }

