package com.tu.clubhub.dev;

import static org.hamcrest.Matchers.hasSize;
import static org.junit.jupiter.api.Assertions.assertNotEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.header;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import java.util.Map;

import com.tu.clubhub.auth.dto.CsrfTokenResponse;
import com.tu.clubhub.club.repository.ClubRepository;
import com.tu.clubhub.committee.repository.ClubCommitteeAssignmentRepository;
import com.tu.clubhub.committee.security.RequireClubCommittee;
import com.tu.clubhub.dashboard.security.AdminAccessService;
import com.tu.clubhub.membership.repository.ClubMembershipRepository;
import com.tu.clubhub.user.repository.StudentProfileRepository;
import com.tu.clubhub.user.repository.UserAccountRepository;
import jakarta.servlet.http.Cookie;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.webmvc.test.autoconfigure.AutoConfigureMockMvc;
import org.springframework.context.annotation.Import;
import org.springframework.http.MediaType;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RestController;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;

@SpringBootTest(properties = "clubhub.dev=true")
@AutoConfigureMockMvc
@ActiveProfiles("test")
@Import(DevAuthIntegrationTest.ProbeController.class)
class DevAuthIntegrationTest {

	private static final String SESSION_COOKIE = "SESSION";

	@Autowired private MockMvc mockMvc;
	@Autowired private ObjectMapper objectMapper;
	@Autowired private ClubCommitteeAssignmentRepository assignmentRepository;
	@Autowired private ClubMembershipRepository membershipRepository;
	@Autowired private ClubRepository clubRepository;
	@Autowired private StudentProfileRepository studentProfileRepository;
	@Autowired private UserAccountRepository userAccountRepository;
	@Autowired private JdbcTemplate jdbcTemplate;

	@BeforeEach
	void resetState() {
		jdbcTemplate.execute("""
				CREATE TABLE IF NOT EXISTS club_categories (
					id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
					name VARCHAR(100) NOT NULL UNIQUE,
					description TEXT
				)
				""");
		assignmentRepository.deleteAll();
		membershipRepository.deleteAll();
		clubRepository.deleteAll();
		jdbcTemplate.update("DELETE FROM club_categories");
		studentProfileRepository.deleteAll();
		userAccountRepository.deleteAll();
	}

	@Test
	void listsAllFourDevRoleAccounts() throws Exception {
		mockMvc.perform(get("/api/v1/auth/dev/accounts"))
				.andExpect(status().isOk())
				.andExpect(header().string("Cache-Control", "no-store"))
				.andExpect(jsonPath("$.accounts", hasSize(4)))
				.andExpect(jsonPath("$.accounts[0].role").value("USER"))
				.andExpect(jsonPath("$.accounts[1].role").value("ADMIN"))
				.andExpect(jsonPath("$.accounts[2].role").value("COMMITTEE"))
				.andExpect(jsonPath("$.accounts[3].role").value("PRESIDENT"));
	}

	@Test
	void switchesAcrossAllFourRolesAndAppliesRealAuthorization() throws Exception {
		CsrfSession session = getCsrfSession(null);

		// 1. Switch to ADMIN -> gains admin access
		MvcResult adminSwitch = switchRole(session, "ADMIN");
		Cookie adminCookie = adminSwitch.getResponse().getCookie(SESSION_COOKIE);
		assertNotNull(adminCookie);
		assertNotEquals(session.cookie().getValue(), adminCookie.getValue());

		mockMvc.perform(get("/api/v1/auth/me").cookie(adminCookie))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.user.role").value("ADMIN"));
		mockMvc.perform(get("/api/v1/test-dev-auth/admin").cookie(adminCookie))
				.andExpect(status().isOk());

		// 2. Switch to COMMITTEE -> auto-provisions club & COMMITTEE assignment
		CsrfSession committeeCsrf = getCsrfSession(adminCookie);
		MvcResult committeeSwitch = switchRole(committeeCsrf, "COMMITTEE");
		Cookie committeeCookie = committeeSwitch.getResponse().getCookie(SESSION_COOKIE);
		assertNotNull(committeeCookie);
		JsonNode committeeBody = objectMapper.readTree(committeeSwitch.getResponse().getContentAsString());
		String clubId = committeeBody.path("user").path("activeCommitteeAssignments").get(0).path("clubId").asText();

		mockMvc.perform(get("/api/v1/test-dev-auth/admin").cookie(committeeCookie))
				.andExpect(status().isForbidden());
		mockMvc.perform(get("/api/v1/test-dev-auth/clubs/" + clubId + "/committee").cookie(committeeCookie))
				.andExpect(status().isOk());

		// 3. Switch to PRESIDENT -> auto-provisions PRESIDENT assignment on the same club
		CsrfSession presidentCsrf = getCsrfSession(committeeCookie);
		MvcResult presidentSwitch = switchRole(presidentCsrf, "PRESIDENT");
		Cookie presidentCookie = presidentSwitch.getResponse().getCookie(SESSION_COOKIE);
		assertNotNull(presidentCookie);

		mockMvc.perform(get("/api/v1/auth/me").cookie(presidentCookie))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.user.role").value("USER"))
				.andExpect(jsonPath("$.user.activeCommitteeAssignments[0].permissionRole").value("PRESIDENT"));
		mockMvc.perform(get("/api/v1/test-dev-auth/clubs/" + clubId + "/committee").cookie(presidentCookie))
				.andExpect(status().isOk());

		// 4. Switch to USER -> regular student without admin or committee rights
		CsrfSession userCsrf = getCsrfSession(presidentCookie);
		MvcResult userSwitch = switchRole(userCsrf, "USER");
		Cookie userCookie = userSwitch.getResponse().getCookie(SESSION_COOKIE);
		assertNotNull(userCookie);

		mockMvc.perform(get("/api/v1/auth/me").cookie(userCookie))
				.andExpect(status().isOk())
				.andExpect(jsonPath("$.user.role").value("USER"))
				.andExpect(jsonPath("$.user.studentStatus").value("ACTIVE"))
				.andExpect(jsonPath("$.user.activeCommitteeAssignments", hasSize(0)));
		mockMvc.perform(get("/api/v1/test-dev-auth/clubs/" + clubId + "/committee").cookie(userCookie))
				.andExpect(status().isForbidden());
		mockMvc.perform(get("/api/v1/test-dev-auth/admin").cookie(userCookie))
				.andExpect(status().isForbidden());
	}

	@Test
	void rejectsMissingCsrfAndInvalidRole() throws Exception {
		mockMvc.perform(post("/api/v1/auth/dev/switch")
				.contentType(MediaType.APPLICATION_JSON)
				.content("{\"role\":\"USER\"}"))
				.andExpect(status().isForbidden())
				.andExpect(jsonPath("$.code").value("CSRF_INVALID"));

		CsrfSession session = getCsrfSession(null);
		mockMvc.perform(post("/api/v1/auth/dev/switch")
				.cookie(session.cookie())
				.header(session.csrf().headerName(), session.csrf().token())
				.contentType(MediaType.APPLICATION_JSON)
				.content("{\"role\":\"SUPERUSER\"}"))
				.andExpect(status().isBadRequest())
				.andExpect(jsonPath("$.code").value("VALIDATION_FAILED"));
	}

	private MvcResult switchRole(CsrfSession session, String role) throws Exception {
		return mockMvc.perform(post("/api/v1/auth/dev/switch")
				.cookie(session.cookie())
				.header(session.csrf().headerName(), session.csrf().token())
				.contentType(MediaType.APPLICATION_JSON)
				.content("{\"role\":\"" + role + "\"}"))
				.andExpect(status().isOk())
				.andExpect(header().string("Cache-Control", "no-store"))
				.andReturn();
	}

	private CsrfSession getCsrfSession(Cookie existingCookie) throws Exception {
		var request = get("/api/v1/auth/csrf");
		if (existingCookie != null) {
			request.cookie(existingCookie);
		}
		MvcResult result = mockMvc.perform(request)
				.andExpect(status().isOk())
				.andReturn();
		Cookie cookie = result.getResponse().getCookie(SESSION_COOKIE);
		CsrfTokenResponse csrf = objectMapper.readValue(
				result.getResponse().getContentAsString(), CsrfTokenResponse.class);
		return new CsrfSession(cookie != null ? cookie : existingCookie, csrf);
	}

	private record CsrfSession(Cookie cookie, CsrfTokenResponse csrf) {
	}

	@RestController
	static class ProbeController {
		private final AdminAccessService adminAccessService;

		ProbeController(AdminAccessService adminAccessService) {
			this.adminAccessService = adminAccessService;
		}

		@GetMapping("/api/v1/test-dev-auth/admin")
		Map<String, String> adminOnly() {
			adminAccessService.requireAdmin();
			return Map.of("ok", "admin");
		}

		@GetMapping("/api/v1/test-dev-auth/clubs/{clubId}/committee")
		@RequireClubCommittee
		Map<String, String> committeeOnly(@PathVariable Long clubId) {
			return Map.of("ok", "committee");
		}
	}
}
